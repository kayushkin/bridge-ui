// Writes src/emojiData.ts, the unicode emoji the Conversations composer's
// picker offers, from the `unicode-emoji-json` package (a devDependency, so
// the page ships only the compact table this writes, not the package).
//
//   node scripts/generate-emoji-data.mjs
//
// Emoji newer than MAX_EMOJI_VERSION are left out: the fonts most readers have
// draw them as empty boxes.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const MAX_EMOJI_VERSION = 15.0
const require = createRequire(import.meta.url)
const groups = JSON.parse(readFileSync(require.resolve('unicode-emoji-json/data-by-group.json'), 'utf8'))
const packageVersion = JSON.parse(readFileSync(require.resolve('unicode-emoji-json/package.json'), 'utf8')).version

const lines = [
  '// AUTO-GENERATED by scripts/generate-emoji-data.mjs from unicode-emoji-json',
  `// ${packageVersion}, emoji version ${MAX_EMOJI_VERSION} and older. Do not edit; run the script.`,
  '',
  '/** Each group of the picker: its name, then its emoji as [emoji, name] in Unicode order,',
  ' *  with a third element 1 when the emoji takes a skin tone modifier. */',
  'export const EMOJI_GROUPS: readonly { name: string; emojis: readonly (readonly [string, string, 1?])[] }[] = [',
]
for (const group of groups) {
  const emojis = group.emojis.filter(e => parseFloat(e.emoji_version) <= MAX_EMOJI_VERSION)
  if (emojis.length === 0) continue
  lines.push(`  { name: ${JSON.stringify(group.name)}, emojis: [`)
  for (const e of emojis) lines.push(`    [${JSON.stringify(e.emoji)}, ${JSON.stringify(e.name)}${e.skin_tone_support ? ', 1' : ''}],`)
  lines.push('  ] },')
}
lines.push(']', '')
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'emojiData.ts')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}`)
